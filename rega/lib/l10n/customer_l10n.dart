/// REGA Customer — ku / ar / en
/// Keys are Kurdish source strings (same pattern as existing UI).
class CustomerL10n {
  CustomerL10n._();

  /// Normalize saved codes: ckb → ku, display names → codes.
  static String normalizeLang(String raw) {
    final v = raw.trim();
    if (v == 'ckb' || v == 'کوردی' || v == 'ku') return 'ku';
    if (v == 'ar' || v == 'العربية') return 'ar';
    if (v == 'en' || v == 'English') return 'en';
    return 'ku';
  }

  static String displayName(String code) {
    switch (normalizeLang(code)) {
      case 'ar':
        return 'العربية';
      case 'en':
        return 'English';
      default:
        return 'کوردی';
    }
  }

  static TextDirection directionFor(String code) =>
      normalizeLang(code) == 'en' ? TextDirection.ltr : TextDirection.rtl;

  static String tr(String key, String lang) {
    final code = normalizeLang(lang);
    final row = _dict[key];
    if (row == null) return key;
    return row[code] ?? row['ku'] ?? key;
  }

  /// Pick a trilingual entity name for the current locale.
  /// Prefer locale field, then fall back: en→ku→ar, ar→ku→en, ku→en→ar.
  static String entityName({
    String? nameKu,
    String? nameAr,
    String? nameEn,
    required String lang,
  }) {
    String? clean(String? v) {
      final t = v?.trim();
      if (t == null || t.isEmpty) return null;
      return t;
    }

    final ku = clean(nameKu);
    final ar = clean(nameAr);
    final en = clean(nameEn);

    switch (normalizeLang(lang)) {
      case 'en':
        return en ?? ku ?? ar ?? '';
      case 'ar':
        return ar ?? ku ?? en ?? '';
      default:
        return ku ?? en ?? ar ?? '';
    }
  }

  /// Convenience when names come from an API map (`name_ku` / `name_ar` / `name_en`).
  static String entityNameFromMap(Map<String, dynamic>? map, String lang) {
    if (map == null) return '';
    return entityName(
      nameKu: map['name_ku']?.toString(),
      nameAr: map['name_ar']?.toString(),
      nameEn: map['name_en']?.toString(),
      lang: lang,
    );
  }

